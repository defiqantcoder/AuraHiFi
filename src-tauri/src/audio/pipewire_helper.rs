//! Optional PipeWire & WirePlumber Bit-Perfect drop-in config generator for Ubuntu 24.04 & 26.04 LTS.
//!
//! Produces `50-bitperfect-dac.conf` and `50-disable-auto-dac.conf` matched to the active
//! DAC's `/proc/asound/card<N>/stream0` sample rates and stable ALSA card ID.

use crate::models::{AudioDeviceInfo, GeneratedPipeWireConfigs};

fn extract_card_id(alsa_id: &str) -> &str {
    if let Some(after_card) = alsa_id.split("CARD=").nth(1) {
        after_card.split(',').next().unwrap_or("ExternalDAC")
    } else {
        "ExternalDAC"
    }
}

pub fn generate_pipewire_configs(
    device: Option<&AudioDeviceInfo>,
    ring_buffer_mb: u32,
) -> GeneratedPipeWireConfigs {
    let default_rates = [44100_u32, 48000, 88200, 96000, 176400, 192000];
    let rates: &[u32] = device
        .map(|d| d.supported_sample_rates.as_slice())
        .filter(|r| !r.is_empty())
        .unwrap_or(&default_rates);

    let alsa_id = device
        .map(|d| d.alsa_id.as_str())
        .unwrap_or("hw:CARD=Bifrost2,DEV=0");
    let card_id = extract_card_id(alsa_id);
    let display_name = device
        .map(|d| d.display_name.as_str())
        .unwrap_or("External USB DAC");
    let usb_vid_pid = device
        .and_then(|d| d.usb_vid_pid.as_deref())
        .unwrap_or("USB Audio Class 2.0");

    let rates_list = rates
        .iter()
        .map(|r| r.to_string())
        .collect::<Vec<_>>()
        .join(" ");
    let default_rate = rates[0];
    let alsa_node_pattern = format!("alsa_output.usb-*{card_id}*");

    let pipewire_content = format!(
        "# Generated by AuraHiFi for Ubuntu 24.04 / 26.04 LTS\n\
# Active DAC: {display_name} ({alsa_id})\n\
# Install to: ~/.config/pipewire/pipewire.conf.d/50-bitperfect-dac.conf\n\
\n\
context.properties = {{\n\
    default.clock.rate          = {default_rate}\n\
    default.clock.allowed-rates = [ {rates_list} ]\n\
    default.clock.quantum       = 1024\n\
    default.clock.min-quantum   = 256\n\
    default.clock.max-quantum   = 4096\n\
    # AuraHiFi ring buffer target: {ring_buffer_mb} MB lock-free PCM/DSD\n\
    link.max-buffers            = 64\n\
}}\n"
    );

    let wireplumber_content = format!(
        "# Generated by AuraHiFi — Prevent PipeWire/WirePlumber from auto-grabbing DAC\n\
# Active DAC: {display_name} ({usb_vid_pid})\n\
# Install to: ~/.config/wireplumber/wireplumber.conf.d/50-disable-auto-dac.conf\n\
\n\
monitor.alsa.rules = [\n\
  {{\n\
    matches = [\n\
      {{\n\
        alsa.card_name = \"~.*{card_id}.*\"\n\
      }}\n\
      {{\n\
        node.name = \"~{alsa_node_pattern}\"\n\
      }}\n\
    ]\n\
    actions = {{\n\
      update-props = {{\n\
        node.pause-on-idle     = true\n\
        session.suspend-timeout-seconds = 1\n\
        priority.driver        = 100\n\
        priority.session       = 100\n\
        api.alsa.disable-batch = false\n\
      }}\n\
    }}\n\
  }}\n\
]\n"
    );

    GeneratedPipeWireConfigs {
        pipewire_file_path: "~/.config/pipewire/pipewire.conf.d/50-bitperfect-dac.conf".into(),
        pipewire_content,
        wireplumber_file_path: "~/.config/wireplumber/wireplumber.conf.d/50-disable-auto-dac.conf"
            .into(),
        wireplumber_content,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::models::{DsdCapability, ReservationStatus, TransportType};

    #[test]
    fn generates_configs_with_stream0_rates_and_card_id() {
        let dev = AudioDeviceInfo {
            alsa_id: "hw:CARD=iFiAudio,DEV=0".into(),
            short_id: "hw:iFiZENDAC".into(),
            card_index: 3,
            vendor: "iFi audio".into(),
            display_name: "iFi ZEN DAC V2".into(),
            usb_vid_pid: Some("20B1:3008".into()),
            transport_type: TransportType::Usb,
            supported_sample_rates: vec![44100, 48000, 96000, 192000, 384000],
            supported_bit_depths: vec![16, 24, 32],
            dsd_capability: DsdCapability::Native,
            max_dsd_multiplier: Some(256),
            reservation_status: ReservationStatus::ReservedByAurahifi,
            holding_process: None,
            holding_pid: None,
            is_isolated_internal: false,
            supports_hardware_volume: true,
            iec958_passthrough: false,
            stream0_path: Some("/proc/asound/card3/stream0".into()),
            dac_chipset: "Burr-Brown".into(),
        };

        let cfg = generate_pipewire_configs(Some(&dev), 128);
        assert!(cfg
            .pipewire_content
            .contains("default.clock.allowed-rates = [ 44100 48000 96000 192000 384000 ]"));
        assert!(cfg
            .wireplumber_content
            .contains("alsa.card_name = \"~.*iFiAudio.*\""));
        assert!(cfg.pipewire_file_path.ends_with("50-bitperfect-dac.conf"));
        assert!(cfg
            .wireplumber_file_path
            .ends_with("50-disable-auto-dac.conf"));
    }
}
